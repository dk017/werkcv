// Builds the extension from the repository: the matcher bundle, the packaged register and the store upload zip.
//
//   node chrome-extension/werkcv-visa-sponsor-checker/build.mjs                 bundle + register from the IND page + zip
//   node chrome-extension/werkcv-visa-sponsor-checker/build.mjs --ind page.html use a saved copy of the IND page
//   node chrome-extension/werkcv-visa-sponsor-checker/build.mjs --no-data       bundle + zip, keep data/register.json
//   node chrome-extension/werkcv-visa-sponsor-checker/build.mjs --icons         also redraw icons/ from icons/icon.svg
//
// The bundle and the data file are committed, so "Load unpacked" works on a fresh checkout without a build.

import { mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";

const root = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(root, "../..");
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : null;
};

const IND_REGISTER_URL = "https://ind.nl/nl/openbaar-register-erkende-referenten/openbaar-register-arbeid";
const MIN_ENTRIES = 10_000;

async function bundleMatcher() {
  await build({
    entryPoints: [path.join(root, "src/sponsor-lib.ts")],
    outfile: path.join(root, "lib/sponsor.js"),
    bundle: true,
    format: "iife",
    target: "chrome116",
    legalComments: "none",
    banner: { js: "// Generated by build.mjs from lib/sponsor in the WerkCV repository. Do not edit by hand." },
  });
  console.log("lib/sponsor.js written");
}

/** A Node build of the register parser and data builder, imported from a temp file. */
async function loadDataTools() {
  const outfile = path.join(tmpdir(), `werkcv-sponsor-data-${process.pid}.mjs`);
  await build({
    stdin: {
      contents: `export { parseIndRegisterHtml } from "./lib/sponsor/register";\nexport { buildExtensionData } from "./lib/sponsor/extension-data";`,
      resolveDir: repo,
      loader: "ts",
    },
    outfile,
    bundle: true,
    format: "esm",
    platform: "node",
  });
  try {
    return await import(pathToFileURL(outfile).href);
  } finally {
    await rm(outfile, { force: true });
  }
}

async function writeData() {
  const { parseIndRegisterHtml, buildExtensionData } = await loadDataTools();
  const file = option("--ind");
  const html = file
    ? await readFile(path.resolve(file), "utf8")
    : await fetch(IND_REGISTER_URL, { headers: { "User-Agent": "WerkCV sponsor checker build (https://werkcv.nl; contact@werkcv.nl)" } }).then((response) => {
        if (!response.ok) throw new Error(`IND responded ${response.status}`);
        return response.text();
      });
  const register = parseIndRegisterHtml(html);
  if (register.entries.length < MIN_ENTRIES) throw new Error(`Only ${register.entries.length} register entries; expected at least ${MIN_ENTRIES}`);
  const data = buildExtensionData(register);
  // One entry per line keeps the committed file readable in a diff when the IND adds or removes employers.
  const { entries, ...rest } = data;
  const json = JSON.stringify(rest).replace(/}$/, `,"entries":[\n${entries.map((entry) => JSON.stringify(entry)).join(",\n")}\n]}`);
  await writeFile(path.join(root, "data/register.json"), `${json}\n`);
  console.log(`data/register.json written: ${entries.length} entries, register date ${data.registerDate}`);
}

async function drawIcons() {
  const sharp = (await import("sharp")).default;
  const svg = await readFile(path.join(root, "icons/icon.svg"));
  for (const size of [16, 32, 48, 128]) {
    await sharp(svg, { density: 384 }).resize(size, size).png().toFile(path.join(root, `icons/icon-${size}.png`));
  }
  console.log("icons written");
}

const PACKAGED = [
  "manifest.json",
  "background.js",
  "check-page.js",
  "popup.html",
  "popup.css",
  "popup.js",
  "lib/sponsor.js",
  "shared/lines.js",
  "data/register.json",
  "content/common.js",
  "content/linkedin.js",
  "content/indeed.js",
  "content/badges.css",
  "_locales/en/messages.json",
  "_locales/nl/messages.json",
  "icons/icon-16.png",
  "icons/icon-32.png",
  "icons/icon-48.png",
  "icons/icon-128.png",
];

async function writeZip() {
  const JSZip = (await import("jszip")).default;
  const manifest = JSON.parse(await readFile(path.join(root, "manifest.json"), "utf8"));
  const zip = new JSZip();
  for (const file of PACKAGED) zip.file(file, await readFile(path.join(root, file)));
  const out = path.join(root, "dist", `werkcv-visa-sponsor-checker-${manifest.version}.zip`);
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE", compressionOptions: { level: 9 } }));
  console.log(`${path.relative(repo, out)} written`);
}

await bundleMatcher();
if (!flag("--no-data")) await writeData();
if (flag("--icons")) await drawIcons();
await writeZip();
